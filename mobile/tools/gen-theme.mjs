// Generates src/theme/tokens.ts from the web user app's design tokens
// (../app/src/tokens.css), so the phone and the web share one source of
// truth for the "Screening Room" colours and radii. Run: npm run gen:theme
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../app/src/tokens.css');
const out = resolve(here, '../src/theme/tokens.ts');
const css = readFileSync(src, 'utf8');

function block(selector) {
  const i = css.indexOf(selector + ' {');
  if (i < 0) throw new Error(`${selector} not found in tokens.css`);
  return css.slice(i, css.indexOf('}', i));
}
function vars(text) {
  const m = {};
  for (const [, name, value] of text.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)) m[name] = value.trim();
  return m;
}
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const dark = vars(block(':root'));
const light = vars(block(":root[data-theme='light']"));
const compact = vars(block('@media (max-width: 760px)').replace(/^[^{]*\{/, ''));

const colorKeys = Object.keys(light).filter((k) => /^#|^rgba?\(/.test(light[k]));
const colors = (m) =>
  Object.fromEntries(colorKeys.map((k) => {
    if (!(k in m)) throw new Error(`--${k} missing from a theme`);
    return [camel(k), m[k]];
  }));
const px = (v) => {
  const n = /^(\d+(?:\.\d+)?)px$/.exec(v);
  if (!n) throw new Error(`not a px value: ${v}`);
  return Number(n[1]);
};

const tokens = {
  dark: colors(dark),
  light: colors(light),
  radius: { panel: px(dark['radius-panel']), hero: px(dark['radius-hero']) },
  gutter: { compact: px(compact.gutter ?? dark.gutter), wide: px(dark.gutter) },
};

writeFileSync(
  out,
  `// Generated by tools/gen-theme.mjs from app/src/tokens.css. Do not edit.\n` +
    `// Run \`npm run gen:theme\` after changing the web tokens.\n\n` +
    `export const tokens = ${JSON.stringify(tokens, null, 2)} as const;\n\n` +
    `export type ColorName = keyof typeof tokens.dark;\n`,
);
console.log(`wrote ${out}`);
