// Lets the app talk plain HTTP to the home-network metareel URL, and to
// nothing else (docs/mobile-app-plan.md, section 7).
//
// iOS: NSAllowsLocalNetworking allows HTTP to local hosts (.local names,
// private IPs) while App Transport Security keeps requiring HTTPS everywhere
// else; NSLocalNetworkUsageDescription explains the Local Network prompt.
//
// Android: a network security config that refuses cleartext by default and
// allows it only for the configured hosts (plus localhost and the emulator's
// host alias, which development builds use for Metro). Android 17 also
// needs ACCESS_LOCAL_NETWORK to reach a LAN address at all; the app asks for
// it when a home address is saved (src/net/local-network.ts).
const { withInfoPlist, withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const DEV_HOSTS = ['localhost', '127.0.0.1', '10.0.2.2', '10.0.3.2'];

function networkSecurityXml(hosts) {
  const domains = [...new Set([...DEV_HOSTS, ...hosts])]
    .map((h) => `        <domain includeSubdomains="false">${h}</domain>`)
    .join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-home-http.js. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
${domains}
    </domain-config>
</network-security-config>
`;
}

module.exports = function withHomeHttp(config, { hosts = [] } = {}) {
  for (const h of hosts) {
    if (!/^[A-Za-z0-9.-]+$/.test(h)) throw new Error(`with-home-http: invalid host "${h}"`);
  }
  config = withInfoPlist(config, (c) => {
    const ats = c.modResults.NSAppTransportSecurity ?? {};
    c.modResults.NSAppTransportSecurity = { ...ats, NSAllowsLocalNetworking: true };
    c.modResults.NSLocalNetworkUsageDescription =
      'metareel connects to your server directly when you are on your home network.';
    return c;
  });
  config = withDangerousMod(config, [
    'android',
    async (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'network_security_config.xml'), networkSecurityXml(hosts));
      return c;
    },
  ]);
  config = withAndroidManifest(config, (c) => {
    AndroidConfig.Permissions.ensurePermissions(c.modResults, ['android.permission.ACCESS_LOCAL_NETWORK']);
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(c.modResults);
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    delete app.$['android:usesCleartextTraffic'];
    return c;
  });
  return config;
};

module.exports.networkSecurityXml = networkSecurityXml;
